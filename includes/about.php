                        <h2 class="text-3xl font-bold text-gray-900 mb-6 border-b-2 border-cwd-blue pb-3">History</h2>
                        <div class="space-y-6 text-gray-700 leading-relaxed">
                            <p>
                                In 1926, the water supply system in Calamba was managed by the Municipal Government, under the administration of the National Water Sewerage Authority (NAWASA), through the then called Calamba Water Works System with Tigbe Spring as the sole source of water that supplied the whole town.
                            </p>
                            <p>
                                Come 1964, Bucal Spring was utilized with approximately 16.4 kilometers of pipelines and a 380 cubic meter concrete reservoir.
                            </p>
                            <p>
                                The creation of The Provincial Water Utilities Act of 1973, also known as Presidential Decree No. 198 (PD 198), paved the way for the birth of various local water districts in the country. On August 07, 1974, the Sangguniang Bayan of Calamba, headed by then Mayor Taciano Rizal, passed Municipal Board Resolution No. 82 Series of 1974 in pursuant to PD 198, as amended, which gave rise to the <span class="font-bold text-cwd-blue">Calamba Water District (CWD)</span>.
                            </p>
                            <p>
                                Two years after, the Local Water Utilities Administration awarded the Conditional Certificate of Conformance No. 29 on September 04, 1976, which entitled CWD to the rights and privileges authorized under PD 198. This then pronounced the official day of CWD in carrying out its mission, which at that time provided service to a total of 1,100 active service connections.
                            </p>
                            <p>
                                Safe drinking water is what CWD guarantees to its concessionaires by supplying potable water conforming to the standards specified in the PNSDW 2007 and as certified by the City Health Office through our DOH-Accredited Laboratory (Accreditation No. 254). With the use of the latest technology, CWD continues to commit to good service for the community and to capture the satisfaction of its concessionaires.
                            </p>
