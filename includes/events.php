<!-- Simple JavaScript for Tab Functionality -->
<script>
  document.addEventListener('DOMContentLoaded', function() {
    const buttons = document.querySelectorAll('[data-tab]');
    const panels = document.querySelectorAll('.tab-panel');

    buttons.forEach(button => {
      button.addEventListener('click', () => {
        const targetTab = button.getAttribute('data-tab');
        
        // Remove active class from all buttons and panels
        buttons.forEach(btn => btn.classList.remove('active-tab', 'bg-cwd-blue', 'text-white', 'shadow-md'));
        buttons.forEach(btn => btn.classList.add('bg-gray-100', 'text-gray-700'));
        panels.forEach(panel => panel.classList.remove('active'));
        
        // Add active class to clicked button and corresponding panel
        button.classList.add('active-tab', 'bg-cwd-blue', 'text-white', 'shadow-md');
        button.classList.remove('bg-gray-100', 'text-gray-700');
        document.getElementById(targetTab + '-tab').classList.add('active');

        // Optional: auto-scroll top of content on tab switch
        const contentTop = document.getElementById(targetTab + '-tab').getBoundingClientRect().top + window.scrollY - 80;
        window.scrollTo({ top: contentTop, behavior: 'smooth' });
      });
    });
  });
</script>

